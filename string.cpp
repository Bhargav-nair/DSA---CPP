// # 9. Loops

// Used to repeat a block of code.

// * for loop
// * while loop
// * do-while loop

// ---

// # 10. Functions

// A function is a reusable block of code designed to perform a specific task.

// ### Advantages

// * Code reusability
// * Better readability
// * Easier debugging
// * Modular programming

// ---

// # 11. Function Arguments

// * Pass by Value

//   * Original value remains unchanged.

// * Pass by Reference

//   * Original value is modified.

// ---

// # 12. Arrays

// An array is a collection of elements of the same data type stored in contiguous memory locations.

// ### Advantages

// * Fast indexing
// * Easy traversal

// ### Disadvantages

// * Fixed size
// * Insertion and deletion are costly

// ---

// # 13. Strings

// A string is a sequence of characters.

// ### Common Operations

// * Length
// * Concatenation
// * Comparison
// * Reverse
// * Substring
// * Search

// ---

// # 14. Pointers

// A pointer stores the memory address of another variable.

// ### Uses

// * Dynamic memory allocation
// * Efficient function calls
// * Linked lists
// * Trees
// * Graphs

// ---

// # 15. References

// A reference is another name (alias) for an existing variable.

// ### Advantages

// * Faster than copying data
// * Used in pass-by-reference
// * Cleaner syntax than pointers in many cases

// ---

// # 16. Dynamic Memory Allocation

// Memory is allocated during runtime.

// Uses:

// * Create arrays of variable size
// * Build dynamic data structures

// ---

// # 17. Object-Oriented Programming (OOP)

// ### Class

// Blueprint for creating objects.

// ### Object

// Instance of a class.

// ### Encapsulation

// Combining data and functions into a single unit.

// ### Abstraction

// Showing only essential details while hiding implementation.

// ### Inheritance

// One class acquires properties of another class.

// ### Polymorphism

// One interface, multiple implementations.

// ---

// # 18. STL (Standard Template Library)

// A collection of pre-built data structures and algorithms.

// ### Containers

// * Vector
// * Stack
// * Queue
// * Deque
// * List
// * Set
// * Map
// * Unordered Set
// * Unordered Map
// * Priority Queue

// ### Algorithms

// * Sorting
// * Searching
// * Reversing
// * Counting
// * Binary Search
// * Maximum/Minimum
// * Accumulate

// ---

// # 19. Time Complexity (Big-O)

// Measures how an algorithm grows with input size.

// ### Common Complexities

// * **O(1)** – Constant
// * **O(log n)** – Logarithmic
// * **O(n)** – Linear
// * **O(n log n)** – Efficient sorting
// * **O(n²)** – Nested loops
// * **O(2ⁿ)** – Exponential
// * **O(n!)** – Factorial

// ---

// # 20. Space Complexity

// Measures the amount of extra memory used by an algorithm.

// ---

