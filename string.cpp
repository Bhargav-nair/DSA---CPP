// * Sliding Window
// * Prefix Sum
// * Hashing
// * Binary Search
// * Recursion
// * Backtracking
// * Greedy
// * Dynamic Programming
// * Graph Traversal (BFS/DFS)

// ---

// # 22. Competitive Programming Tips

// * Prefer STL over writing everything from scratch.
// * Analyze **time and space complexity** before coding.
// * Handle edge cases (empty input, single element, duplicates, negative numbers).
// * Use meaningful variable names while learning.
// * Practice dry-running algorithms on paper before implementation.

